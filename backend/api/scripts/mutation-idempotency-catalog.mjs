#!/usr/bin/env node
/**
 * Mutation idempotency catalog (audit R78).
 *
 * Scans every HTTP mutation route (POST/PUT/PATCH/DELETE) registered via
 * `app.<method>('/path'` across src/ and classifies the idempotency
 * mechanism its handler body uses. Emits docs/MUTATION_IDEMPOTENCY.md.
 *
 * Classification is heuristic — it detects the mechanism, not correctness:
 *   idempotency-key   — Idempotency-Key / idempotencyKey / request hash dedupe
 *   on-conflict       — INSERT ... ON CONFLICT natural-key dedupe
 *   state-machine     — terminal-state / status guards (already-terminal no-ops)
 *   locked-update     — SELECT ... FOR UPDATE row locking (safe retry, not idempotent)
 *   unguarded         — no mechanism detected; needs review
 *
 * Usage: node scripts/mutation-idempotency-catalog.mjs [--check]
 *   --check  exit 1 when a money-path route is classified unguarded.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'src');
const OUT = path.join(SRC, 'docs', 'MUTATION_IDEMPOTENCY.md');
const ROUTE_RE = /app\.(post|put|patch|delete)\(\s*['"`]([^'"`]+)['"`]/g;
const ANY_ROUTE_RE = /app\.(get|post|put|patch|delete|head|options)\(\s*['"`]/;
const WINDOW = 400; // lines of handler body scanned per route

const MONEY_PATH = /payment|wallet|payout|withdraw|refund|order|checkout|transfer|co-?own|auction|bid|settle|ledger|deposit|mint|burn|convert/i;

const MECHANISMS = [
  ['idempotency-key', /idempotency[-_]?key|idempotencyKey|Idempotency-Key|request_hash|requestHash|dedupe_?key|dedupeKey|commandInsert|coown_order_commands/i],
  ['on-conflict', /ON\s+CONFLICT/i],
  ['state-machine', /terminal|already.*processed|status\s*!?=+\s*'|status\s+IN\s*\(|checkTransition|canTransition|assertTransition|isTerminalState|WHERE\s+[^)]*status\s*=\s*'/i],
  ['locked-update', /FOR\s+UPDATE/i],
];

function collectFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === '__tests__' || entry.name === 'integration' || entry.name === 'docs' || entry.name === 'scripts') continue;
      out.push(...collectFiles(full));
    } else if (entry.name.endsWith('.ts')) {
      out.push(full);
    }
  }
  return out;
}

function classify(handlerBody) {
  const hits = MECHANISMS.filter(([, re]) => re.test(handlerBody)).map(([name]) => name);
  return hits.length ? hits : ['unguarded'];
}

const routes = [];
for (const file of collectFiles(SRC)) {
  const src = readFileSync(file, 'utf8');
  const lines = src.split('\n');
  const rel = path.relative(SRC, file).replace(/\\/g, '/');
  for (let i = 0; i < lines.length; i++) {
    ROUTE_RE.lastIndex = 0;
    const m = ROUTE_RE.exec(lines[i]);
    if (!m) continue;
    // Handler body ends at the next route declaration or WINDOW lines,
    // whichever comes first — prevents one route's guard markers from
    // bleeding into its neighbour's classification.
    let end = Math.min(i + WINDOW, lines.length);
    for (let j = i + 1; j < end; j++) {
      if (ANY_ROUTE_RE.test(lines[j])) { end = j; break; }
    }
    const body = lines.slice(i, end).join('\n');
    routes.push({
      method: m[1].toUpperCase(),
      path: m[2],
      file: rel,
      line: i + 1,
      mechanisms: classify(body),
    });
  }
}

routes.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);

const counts = {};
for (const r of routes) {
  const key = r.mechanisms[0] === 'unguarded' && r.mechanisms.length === 1 ? 'unguarded' : r.mechanisms.join('+');
  counts[key] = (counts[key] ?? 0) + 1;
}

const unguardedMoney = routes.filter(
  (r) => r.mechanisms.length === 1 && r.mechanisms[0] === 'unguarded' && MONEY_PATH.test(r.path),
);

let md = `# Mutation idempotency catalog (R78)

Generated by \`scripts/mutation-idempotency-catalog.mjs\` — do not hand-edit.

**${routes.length} mutation routes** scanned. Mechanism detection is
heuristic: a route marked \`unguarded\` needs review, not necessarily a fix
(some handlers are naturally idempotent via upserts or state guards the
scanner cannot see).

| Mechanism | Routes |
|---|---|
${Object.entries(counts)
  .sort((a, b) => b[1] - a[1])
  .map(([k, v]) => `| ${k} | ${v} |`)
  .join('\n')}

## Money-path routes with no detected idempotency mechanism

${unguardedMoney.length === 0 ? 'None detected.' : unguardedMoney.map((r) => `- \`${r.method} ${r.path}\` — ${r.file}:${r.line}`).join('\n')}

## Full catalog

| Method | Path | Mechanism | Location |
|---|---|---|---|
${routes.map((r) => `| ${r.method} | \`${r.path}\` | ${r.mechanisms.join(', ')} | ${r.file}:${r.line} |`).join('\n')}
`;

mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, md);

console.log(`catalog: ${routes.length} routes → ${path.relative(process.cwd(), OUT)}`);
console.log(`unguarded money-path routes: ${unguardedMoney.length}`);

if (process.argv.includes('--check') && unguardedMoney.length > 0) {
  console.error('FAIL: money-path mutations without a detected idempotency mechanism');
  process.exit(1);
}
